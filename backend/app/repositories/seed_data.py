def seed_reference_data(db: Session) -> None:
    """Idempotently seed skills, job roles, role-skill requirements, assessments, questions, and learning activities."""
    for s_data in SKILLS_DATA:
        existing_skill = db.query(Skill).filter(Skill.id == s_data["id"]).one_or_none()
        if not existing_skill:
            db.add(Skill(**s_data))
    db.flush()

    for r_data in ROLES_DATA:
        existing_role = db.query(JobRole).filter(JobRole.id == r_data["id"]).one_or_none()
        if not existing_role:
            role = JobRole(
                id=r_data["id"],
                name=r_data["name"],
                description=r_data["description"],
                version=r_data["version"],
                active=r_data["active"],
            )
            db.add(role)
            db.flush()
            for skill_id, weight, expected_level, rationale in r_data["skills"]:
                db.add(
                    RoleSkillRequirement(
                        role_id=role.id,
                        skill_id=skill_id,
                        weight=weight,
                        expected_level=expected_level,
                        rationale=rationale,
                        version=r_data["version"],
                    )
                )
    db.flush()

    for a_data in ASSESSMENTS_DATA:
        existing_assessment = db.query(Assessment).filter(Assessment.id == a_data["id"]).one_or_none()
        if not existing_assessment:
            db.add(Assessment(**a_data))
    db.flush()

    for q_data in QUESTIONS_DATA:
        existing_q = db.query(Question).filter(Question.id == q_data["id"]).one_or_none()
        if not existing_q:
            q = Question(
                id=q_data["id"],
                assessment_id=q_data["assessment_id"],
                skill_id=q_data["skill_id"],
                topic=q_data["topic"],
                skill_area=q_data["skill_area"],
                question_type=q_data["question_type"],
                question_text=q_data["question_text"],
                difficulty=q_data["difficulty"],
                correct_answer_json=json.dumps(q_data["correct_answer"]),
                explanation=q_data["explanation"],
                score_value=q_data["score_value"],
                version=q_data["version"],
                active=q_data["active"],
            )
            db.add(q)
            db.flush()
            for opt_id, opt_text in q_data["options"]:
                db.add(
                    QuestionOption(
                        question_id=q.id,
                        option_identifier=opt_id,
                        option_text=opt_text,
                    )
                )
    db.flush()

    for act_data in LEARNING_ACTIVITIES_DATA:
        existing_act = db.query(LearningActivity).filter(LearningActivity.id == act_data["id"]).one_or_none()
        if not existing_act:
            db.add(LearningActivity(**act_data, status="active"))

    db.commit()
